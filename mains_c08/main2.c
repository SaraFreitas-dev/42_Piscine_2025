#include <stdio.h>
#include "ft_abs.h"

int main(void)
{
    printf("%d\n", ABS(-10));     // 10
    printf("%d\n", ABS(0));       // 0
    printf("%d\n", ABS(5));       // 5
    printf("%d\n", ABS(3 - 7));   // 4
    printf("%d\n", ABS(2 * -3));  // 6
    return 0;
}

